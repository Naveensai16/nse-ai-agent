# Alias for backwards and external compatibility
STOCK_MASTER = INDIAN_STOCK_MASTER


def get_stock_by_symbol(symbol: str) -> dict[str, Any] | None:
    """Retrieve stock master record by symbol (case-insensitive)."""
    if not symbol:
        return None
    sym_clean = str(symbol).strip().upper().replace(".NS", "")
    return INDIAN_STOCK_MASTER.get(sym_clean)


def search_stock_master(query: str, limit: int = 10) -> list[dict[str, Any]]:
    """Search stock master records by ticker, company name, or alias."""
    if not query or not str(query).strip():
        return []
    q_lower = str(query).strip().lower()
    matches: list[dict[str, Any]] = []
    seen: set[str] = set()

    # Exact symbol prefix
    for sym, data in INDIAN_STOCK_MASTER.items():
        if sym.lower().startswith(q_lower):
            if sym not in seen:
                seen.add(sym)
                matches.append(data)
                if len(matches) >= limit:
                    return matches

    # Name contains
    for sym, data in INDIAN_STOCK_MASTER.items():
        if q_lower in data.get("company_name", "").lower():
            if sym not in seen:
                seen.add(sym)
                matches.append(data)
                if len(matches) >= limit:
                    return matches

    # Aliases
    for sym, data in INDIAN_STOCK_MASTER.items():
        if any(q_lower in a for a in data.get("aliases", [])):
            if sym not in seen:
                seen.add(sym)
                matches.append(data)
                if len(matches) >= limit:
                    return matches

    return matches[:limit]

